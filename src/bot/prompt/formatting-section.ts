/**
 * VK's `messages.send` has no Telegram-style rich-message rendering --
 * `VkBotTurnPublisher` sends whatever text the model produces verbatim, so
 * Markdown syntax the Telegram contract below explicitly teaches (headers,
 * tables, bold/italic, fenced code) would show up as literal asterisks and
 * pipes in a VK chat rather than rendering. VK gets a plain-text contract
 * instead of the Telegram Rich Message one.
 */
export function renderFormattingSection(transport: "telegram" | "vk"): string {
  if (transport === "vk") {
    return `# Форматирование ответа
Финальный ответ публикуется как обычное текстовое сообщение ВКонтакте — Markdown
и HTML не рендерятся и будут видны собеседнику как есть (звёздочки, решётки,
вертикальные черты и т.п. останутся в тексте буквально). Пиши простым текстом:
абзацы через пустую строку, списки — через тире или цифру с точкой на новой
строке, акценты — интонацией и словами, а не разметкой. Ссылки давай как
обычный URL текстом, без markdown-синтаксиса \`[текст](url)\`.`;
  }
  return `# Форматирование ответа
Финальный ответ публикуется как нативное Telegram Rich Message: Telegram сам
рисует заголовки, списки, таблицы и формулы. Поддерживаемая разметка:

- заголовки \`# H1\` … \`###### H6\`;
- упорядоченные \`1.\` и неупорядоченные \`-\`/\`*\` списки, чек-листы
  \`- [ ]\`/\`- [x]\`;
- GFM-таблицы \`| a | b |\` — только компактные: строка заголовка строго перед строкой-разделителем
  (таблица никогда не начинается с \`|---|\`), одинаковое число ячеек в заголовке, разделителе и строках
  данных, максимум 4 короткие колонки; в строке-разделителе каждой ячейке нужны минимум три дефиса:
  \`| :--- | ---: |\`, не \`| :-- | --: |\`. Таблица — не универсальный формат: для сравнений и карточек
  шире 4 колонок используй нумерованные секции или списки;
- inline-формулы \`$...$\`, блочные \`$$...$$\` и fenced \`math\`;
- \`**жирный**\`, \`*курсив*\`, \`_курсив_\`, \`__жирный__\`,
  \`~~зачёркнутый~~\`;
- inline-код \`код\` и fenced-блоки \`\`\`lang ... \`\`\`;
- \`> цитата\`;
- явные ссылки \`[текст](https://…)\` — только https, без логина и пароля.

Запрещено: HTML, картинки и медиа, \`tg://\`, \`mailto:\`, \`tel:\`,
\`javascript:\`, \`data:\` и не-HTTPS ссылки. Если конструкция не
поддерживается, весь ответ уходит plain text — не пытайся обойти разметку.`;
}
