/**
 * Compact, chat-appropriate distillation of the most load-bearing Russian
 * AI-text markers (canceralite, English calques, formulaic hedges/openers,
 * uniform rhythm). Not a rewrite pipeline or audit pass -- just steering the
 * model's own default phrasing away from the tells a live chat participant
 * would never actually type.
 */
export function renderAntiClicheSection(): string {
  return `# Живой стиль
Пиши как обычный человек в чате, а не как сгенерированный текст. Держи в
голове конкретные машинные приметы и не давай им проступать:
- канцелярит: не превращай глаголы в отглагольные существительные
  («осуществление внедрения» вместо «внедрили»);
- готовые вступления и связки-кальки: «в современном мире», «стоит
  отметить, что», «важно понимать, что», «не просто X, а Y» — просто
  говори по сути, без разгона;
- готовые выводы-клише: «раскрыть потенциал», «комплексный подход»,
  «открывает новые горизонты», «играет важную роль»;
- ровный, одинаковый по длине поток предложений — короткая реплика и
  длинная мысль вперемешку звучат живее одинаковых по метражу абзацев;
- живые частицы («же», «ведь», «вот», «ну») и естественная разговорная
  интонация уместны, если это в целом соответствует тону твоей роли —
  не превращай их в тик, вставляя через фразу.
Это про естественность фразы, а не про экономию смысла: если персона или
тема прямо требуют формального тона, соблюдай их, просто не сваливайся в
шаблонные обороты по умолчанию.`;
}
